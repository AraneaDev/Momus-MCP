// E7 — full MCP server + client round-trip over stdio.
// Validates: docs/04 (5 tools, annotations, structuredContent, deterministic order),
// using the official SDK's subpath entries discovered in the SDK probe.
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { z } from 'zod';
import * as ts from 'typescript';
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';
import { detectMocks, tautologyIssues, driftIssues, makeProgram, rel } from './lib/engine.ts';

const ROOT = fileURLToPath(new URL('../fixtures/ts', import.meta.url));
const program = makeProgram(ROOT);

const fmtIssue = (i: { rule: string; severity: string; file: string; line: number; col: number; message: string }) =>
  `- \`${rel(i.file)}:${i.line}:${i.col}\` **${i.rule}** ${i.severity} — ${i.message}`;

function audit(filePath: string) {
  const abs = resolve(ROOT, filePath);
  if (!existsSync(abs)) throw new Error(`NOT_FOUND: ${filePath}`);
  // IMPORTANT: type-aware analysis must use the program's own source file instance,
  // otherwise the checker cannot resolve identifiers (types degrade to `any`).
  const sf = program.getSourceFile(abs) ?? ts.createSourceFile(abs, readFileSync(abs, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const t0 = Date.now();
  const issues = [
    ...tautologyIssues(sf, abs),
    ...driftIssues(sf, abs, program),
  ].sort((a, b) => a.line - b.line || a.col - b.col);
  const durationMs = Date.now() - t0;
  const seen = new Set<string>();
  const deduped = issues.filter((i) => (seen.has(i.rule + ':' + i.line + ':' + i.message) ? false : (seen.add(i.rule + ':' + i.line + ':' + i.message), true)));
  const errors = deduped.filter((i) => i.severity === 'error').length;
  const warnings = deduped.filter((i) => i.severity === 'warning').length;
  const report = `# Momus audit — ${filePath}\nAudited 1 file · ${deduped.length} issues (${errors} error · ${warnings} warning) · ${durationMs}ms\n\n${deduped.map(fmtIssue).join('\n')}`;
  return { report, issues: deduped, summary: { filesAudited: 1, issues: deduped.length, errors, warnings, infos: 0 } };
}

function synthContract(targetPath: string, framework: string) {
  const abs = resolve(ROOT, targetPath);
  if (!existsSync(abs)) throw new Error(`NOT_FOUND: ${targetPath}`);
  const source = readFileSync(abs, 'utf8');
  const sf = ts.createSourceFile(abs, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const cls = sf.statements.find((s) => ts.isClassDeclaration(s) && s.name?.text === 'LedgerService') as ts.ClassDeclaration;
  const contract: string[] = [];
  for (const m of cls.members) {
    if (ts.isMethodDeclaration(m)) {
      const params = m.parameters.map((p) => `${p.name.getText(sf)}${p.type ? ': ' + p.type.getText(sf) : ''}`).join(', ');
      contract.push(`${m.name.getText(sf)}(${params})${m.type ? ': ' + m.type.getText(sf) : ''}`);
    }
  }
  const lines = contract.map((sig) => `  // ${sig}\n  ${sig.split('(')[0]}: vi.fn(),`);
  const template = `// Generated by momus synthesize_mock_contract — LedgerService (${framework})\nconst ledgerMock = {\n${lines.join('\n')}\n} satisfies Partial<LedgerService>;`;
  return { template, contract, summary: { targetPath, symbol: 'LedgerService', framework, members: contract.length } };
}

// ---------------------------------------------------------------- server
async function main() {
  if (process.argv.includes('--serve')) {
    const server = new McpServer({ name: 'momus-mcp', version: '0.1.0' }, { capabilities: { tools: { listChanged: true } } });
    const ann = { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false };
    const annTitled = (title: string) => ({ ...ann, title });

    server.tool('audit_test_fidelity', 'Deep static audit of a test file: mocks vs production contracts, tautological assertions.', {
      filePath: z.string().describe('Test file path, workspace-relative'),
      maxIssues: z.number().int().min(0).max(500).default(50),
    }, annTitled('Audit Test Fidelity'), async ({ filePath }) => {
      const { report, issues, summary } = audit(filePath);
      return { content: [{ type: 'text', text: report }], structuredContent: { schemaVersion: 1, tool: 'audit_test_fidelity', result: { summary, issues } } };
    });

    server.tool('detect_tautological_assertions', 'Scan test files for assertions that cannot fail.', {
      paths: z.array(z.string()).optional(),
      maxIssues: z.number().int().min(0).max(500).default(50),
    }, annTitled('Detect Tautological Assertions'), async ({ paths }) => {
      const filePath = (paths ?? ['tests/ledger.test.ts'])[0];
      const { report, issues, summary } = audit(filePath);
      const taut = issues.filter((i) => i.rule.startsWith('TAUT'));
      return { content: [{ type: 'text', text: report }], structuredContent: { schemaVersion: 1, tool: 'detect_tautological_assertions', result: { summary: { ...summary, issues: taut.length }, issues: taut } } };
    });

    server.tool('verify_mock_drift', 'Scan for test doubles that no longer match production contracts.', {
      scope: z.enum(['workspace', 'git-diff']).default('workspace'),
      baseRef: z.string().optional(),
      maxIssues: z.number().int().min(0).max(500).default(50),
    }, annTitled('Verify Mock Drift'), async ({ scope }) => {
      if (scope === 'git-diff' && !existsSync(resolve(ROOT, '../../.git'))) {
        return { content: [{ type: 'text', text: '## Error\nno git repo in spike fixture; use scope=workspace' }], isError: true };
      }
      const { report, issues, summary } = audit('tests/ledger.test.ts');
      const drift = issues.filter((i) => i.rule.startsWith('DRIFT'));
      return { content: [{ type: 'text', text: report }], structuredContent: { schemaVersion: 1, tool: 'verify_mock_drift', result: { summary: { ...summary, issues: drift.length }, issues: drift } } };
    });

    server.tool('synthesize_mock_contract', 'Generate a strict typed mock template from a production class AST.', {
      targetPath: z.string(),
      framework: z.enum(['vitest', 'jest', 'phpunit', 'pest']),
      includeReturnValues: z.boolean().default(true),
    }, annTitled('Synthesize Mock Contract'), async ({ targetPath, framework }) => {
      const { template, contract, summary } = synthContract(targetPath, framework);
      return { content: [{ type: 'text', text: '```ts\n' + template + '\n```' }], structuredContent: { schemaVersion: 1, tool: 'synthesize_mock_contract', result: { summary, template, contract, notes: [] } } };
    });

    server.tool('list_rules', 'Returns the rule catalog with severities and suppression syntax.', {},
      annTitled('List Rules'), async () => ({
        content: [{ type: 'text', text: '# Rules\n- TAUT-001 self-comparison (error)\n- TAUT-002 mock-echo (error)\n- TAUT-006 unconfigured-spy-assert (warning)\n- DRIFT-001 missing-member (error)\n- DRIFT-003 return-type-mismatch (warning)\n- DRIFT-005 missing-export (error)' }],
        structuredContent: { schemaVersion: 1, tool: 'list_rules', result: { rules: [{ id: 'TAUT-002', severity: 'error' }], suppressionSyntax: '// @momus-ignore[:RULE]', configFile: '.momusrc' } },
      }));

    await server.connect(new StdioServerTransport());
    return;
  }

  // ---------------------------------------------------------------- client
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [resolve(import.meta.dirname, '../node_modules/.bin/tsx'), fileURLToPath(new URL('./e7-mcp-server.ts', import.meta.url)), '--serve'],
  });
  const client = new Client({ name: 'e7-test-client', version: '0.0.1' });
  await client.connect(transport);
  let pass = true;
  const check = (ok: boolean, label: string, extra = '') => {
    console.log(`  ${ok ? 'PASS' : 'FAIL'}  ${label}${extra ? ' — ' + extra : ''}`);
    pass &&= ok;
  };

  const tools = await client.listTools();
  const names = tools.tools.map((t) => t.name);
  check(JSON.stringify(names) === JSON.stringify(['audit_test_fidelity', 'detect_tautological_assertions', 'verify_mock_drift', 'synthesize_mock_contract', 'list_rules']),
    'tools/list: 5 tools, deterministic order', names.join(', '));
  const first = tools.tools[0];
  check(first.annotations?.readOnlyHint === true && first.annotations?.destructiveHint === false && first.annotations?.idempotentHint === true,
    'tool annotations present', JSON.stringify(first.annotations));

  const res = await client.callTool({ name: 'audit_test_fidelity', arguments: { filePath: 'tests/ledger.test.ts' } });
  const sc = res.structuredContent as any;
  const result = sc?.result;
  check(!!result && Array.isArray(result.issues) && result.issues.length === 3, 'audit_test_fidelity: 3 issues via structuredContent', JSON.stringify(result?.issues?.map((i: any) => i.rule)));
  const rules = result?.issues?.map((i: any) => i.rule).sort();
  check(JSON.stringify(rules) === JSON.stringify(['DRIFT-001', 'TAUT-002', 'TAUT-006']),
    'planted violations found', JSON.stringify(rules));

  const taut = await client.callTool({ name: 'detect_tautological_assertions', arguments: {} });
  const tautRules = ((taut.structuredContent as any)?.result?.issues ?? []).map((i: any) => i.rule);
  check(tautRules.includes('TAUT-002') && tautRules.includes('TAUT-006'), 'detect_tautological_assertions: TAUT rules only', JSON.stringify(tautRules));

  const synth = await client.callTool({ name: 'synthesize_mock_contract', arguments: { targetPath: 'src/services/ledger.ts', framework: 'vitest' } });
  const synthRes = (synth.structuredContent as any)?.result;
  check(synthRes?.contract?.length === 2 && synthRes?.template.includes('totalFor'), 'synthesize_mock_contract: contract + template', `${synthRes?.contract?.length} members`);

  const rulesRes = await client.callTool({ name: 'list_rules', arguments: {} });
  check((rulesRes.structuredContent as any)?.result?.rules?.length >= 1, 'list_rules round-trip');

  const err = await client.callTool({ name: 'audit_test_fidelity', arguments: { filePath: 'nope.ts' } });
  check((err as any).isError === true, 'error path: missing file returns isError', String((err as any).isError));

  await client.close();
  console.log(pass ? 'E7 PASS: full MCP surface works over stdio' : 'E7 FAIL');
  process.exit(pass ? 0 : 1);
}

main().catch((e) => { console.error('E7 CRASH:', e.message); process.exit(1); });
